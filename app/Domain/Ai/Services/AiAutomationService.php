<?php

namespace App\Domain\Ai\Services;

use App\Ai\Agents\ThreadLabelingAgent;
use App\Ai\Agents\ThreadSummaryAgent;
use App\Ai\Agents\ThreadTitleAgent;
use App\Ai\Agents\ThreadUrgencyAgent;
use App\Domain\Label\Models\Label;
use App\Domain\Thread\Enums\ActorType;
use App\Domain\Thread\Enums\ThreadPriority;
use App\Domain\Thread\Models\Thread;
use Illuminate\Support\Str;

/**
 * Runs the small, per-thread AI Agent automations (auto-labeling, urgency
 * detection, thread titling, thread catch-up summaries). Each method is
 * safe to call regardless of whether the corresponding AiSettings flag is
 * on — callers (the observer, the on-demand controllers) are expected to
 * check the flag first, but the methods themselves stay defensive.
 */
class AiAutomationService
{
    /**
     * Titles auto-generated by the inbound channel processors — these are
     * treated as "generic" placeholders that thread-titling is allowed to
     * replace. A thread with any other title (e.g. a real email subject
     * line) is left alone.
     */
    private const GENERIC_TITLE_PATTERNS = [
        '/^Email inquiry from /',
        '/^Website chat$/',
        '/^Chat with /',
        '/^Slack support request/',
    ];

    /**
     * Apply any of the team's existing labels that match the thread's
     * content. Never creates new labels. Silently does nothing on an empty
     * match, no available labels, or an agent failure.
     */
    public function applyAutoLabeling(Thread $thread): void
    {
        $labels = Label::where('team_id', $thread->team_id)->orderBy('name')->limit(30)->get();

        if ($labels->isEmpty()) {
            return;
        }

        $message = $this->latestCustomerMessage($thread);

        if (! filled($message)) {
            return;
        }

        $agent = new ThreadLabelingAgent(availableLabels: $labels->pluck('name')->all());
        $response = $agent->prompt("Thread title: {$thread->title}\n\nCustomer message:\n{$message}");

        $matchedNames = collect($response['labels'] ?? [])
            ->map(fn ($name) => Str::lower(trim((string) $name)))
            ->filter()
            ->values();

        if ($matchedNames->isEmpty()) {
            return;
        }

        $matchedIds = $labels
            ->filter(fn (Label $label) => $matchedNames->contains(Str::lower($label->name)))
            ->pluck('id');

        if ($matchedIds->isEmpty()) {
            return;
        }

        $thread->labels()->syncWithoutDetaching($matchedIds->all());
    }

    /**
     * Classify the thread's urgency and set its priority — only if the
     * thread is still at the default priority, so we never clobber a
     * priority a human (or a workflow) has already set explicitly.
     */
    public function detectUrgency(Thread $thread): void
    {
        if ($thread->priority !== ThreadPriority::Normal) {
            return;
        }

        $message = $this->latestCustomerMessage($thread);

        if (! filled($message)) {
            return;
        }

        $agent = new ThreadUrgencyAgent;
        $response = $agent->prompt("Thread title: {$thread->title}\n\nCustomer message:\n{$message}");

        $priority = ThreadPriority::tryFrom((string) ($response['priority'] ?? ''));

        if (! $priority || $priority === ThreadPriority::Normal) {
            return;
        }

        $thread->update(['priority' => $priority]);
    }

    /**
     * Replace a generic, auto-generated thread title with a short
     * description of what the customer is asking about — only if the
     * current title still looks like one of the channel-generated
     * placeholders.
     */
    public function generateTitle(Thread $thread): void
    {
        if (! $this->hasGenericTitle($thread->title)) {
            return;
        }

        $message = $this->latestCustomerMessage($thread);

        if (! filled($message)) {
            return;
        }

        $agent = new ThreadTitleAgent;
        $title = trim((string) $agent->prompt($message)->text);
        $title = trim($title, " \t\n\r\0\x0B\"'");

        if ($title === '') {
            return;
        }

        $thread->update(['title' => Str::limit($title, 60, '')]);
    }

    /**
     * Generate an on-demand "catch me up" summary of the thread's timeline.
     *
     * @throws \Throwable
     */
    public function summarize(Thread $thread): string
    {
        $timeline = $thread->timelineEntries()
            ->whereIn('actor_type', [ActorType::Tenant, ActorType::User, ActorType::Ai])
            ->whereNotNull('body')
            ->orderBy('created_at')
            ->limit(50)
            ->get(['actor_type', 'body'])
            ->map(fn ($entry) => strtoupper($entry->actor_type->value).': '.Str::limit((string) $entry->body, 500))
            ->implode("\n\n");

        if (! filled($timeline)) {
            $timeline = (string) $thread->title;
        }

        $agent = new ThreadSummaryAgent;

        return trim((string) $agent->prompt($timeline)->text);
    }

    private function hasGenericTitle(?string $title): bool
    {
        if (! filled($title)) {
            return true;
        }

        foreach (self::GENERIC_TITLE_PATTERNS as $pattern) {
            if (preg_match($pattern, $title) === 1) {
                return true;
            }
        }

        return false;
    }

    private function latestCustomerMessage(Thread $thread): ?string
    {
        return $thread->timelineEntries()
            ->where('actor_type', ActorType::Tenant)
            ->whereNotNull('body')
            ->latest('created_at')
            ->value('body');
    }
}
